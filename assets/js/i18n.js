const pad2 = (n) => String(n).padStart(2, '0');

function clockEn(p) {
  const h = p.hour % 12 === 0 ? 12 : p.hour % 12;
  return `${h}:${pad2(p.minute)} ${p.hour < 12 ? 'am' : 'pm'}`;
}

function clockZh(p) {
  const h = p.hour % 12 === 0 ? 12 : p.hour % 12;
  return `${p.hour < 12 ? '上午' : '下午'}${h}:${pad2(p.minute)}`;
}

